#!/usr/bin/env python3
"""Validated deterministic level source -> C import. No game data written."""
import json,sys,hashlib
from pathlib import Path
def validate(v):
 assert v['name'] in ['Twin Seals','Twin Seals: Deep Circuit','Deep Circuit: Menagerie'] and v['map']==3,'unsupported name/map'
 rows=v['rows'];h=len(rows);w=len(rows[0]);assert 5<=w<=32 and 5<=h<=32,'dimensions'
 assert all(len(r)==w and set(r)<=set('#.DBF') for r in rows),'unsupported tiles/ragged'
 assert all(c=='#' for c in rows[0]+rows[-1]) and all(r[0]==r[-1]=='#' for r in rows),'solid boundary'
 pts=v['starts']+v['activators']+[v['door']]+v['exits'];assert len(v['starts'])==len(v['activators'])==len(v['exits'])==2,'two parties'
 coords=[]
 for p in pts:
  x,y=p['x'],p['y'];assert type(x)==type(y)==int and 0<x<w-1 and 0<y<h-1,'coordinates'
  assert rows[y][x]!='#','point in wall';coords.append((x,y))
 assert len(set(coords))==len(coords),'overlap'
 assert all(type(p['direction'])==int and 0<=p['direction']<4 for p in v['starts']),'direction'
 d=v['door'];assert rows[d['y']][d['x']]=='D' and sum(r.count('D') for r in rows)==1,'one door'
 def flood(start,opened):
  seen={start};todo=[start]
  for x,y in todo:
   for q in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)]:
    a,b=q
    if q not in seen and 0<=a<w and 0<=b<h and (rows[b][a] in '.BF' or opened and rows[b][a]=='D'):seen.add(q);todo.append(q)
  return seen
 for i,s in enumerate(v['starts']):
  closed=flood((s['x'],s['y']),False);assert (v['activators'][i]['x'],v['activators'][i]['y']) in closed,'activator unreachable'
  assert not any((e['x'],e['y']) in closed for e in v['exits']),'exit bypass'
  opened=flood((s['x'],s['y']),True);assert all((e['x'],e['y']) in opened for e in v['exits']),'exit unreachable'
 encounters=v.get('encounters',[]);assert len(encounters)<=15,'encounter limit'
 for e in encounters:
  assert all(type(e[k])==int for k in ['x','y','type','count','hp','direction']),'encounter integers'
  x,y=e['x'],e['y'];assert 0<x<w-1 and 0<y<h-1 and rows[y][x]=='.','encounter floor'
  assert (x,y) not in coords,'encounter overlap';coords.append((x,y))
  assert e['type'] in [0,1,2,3,6,7,8,9,10,12,13,14,15,17,18] and e['count']==1 and 1<=e['hp']<=100 and 0<=e['direction']<4,'unsupported encounter'
  assert all(abs(x-s['x'])+abs(y-s['y'])>=3 for s in v['starts']),'encounter start clearance'
  assert (x,y) in flood((v['starts'][0]['x'],v['starts'][0]['y']),True),'encounter unreachable'
 if v['name']=='Deep Circuit: Menagerie':
  assert len({e['type'] for e in encounters})==15,'need 15 distinct species'
  def room(e):
   return (sum(e['x']>cut for cut in (6,14,21)),sum(e['y']>cut for cut in (6,13,20)))
  assert len({room(e) for e in encounters})==15 and (0,0) not in {room(e) for e in encounters},'one species per room; clear start'
 for key,tile in [('buttonDoors','B'),('secretWalls','F')]:
  assert len(v.get(key,[]))==sum(r.count(tile) for r in rows),'feature count'
  for p in v.get(key,[]):
   q=(p['x'],p['y']);assert rows[q[1]][q[0]]==tile and q not in coords,'feature collision';coords.append(q)
 for p in v.get('supplies',[]):
  q=(p['x'],p['y']);assert rows[q[1]][q[0]]=='.' and q not in coords,'supply collision';coords.append(q)
  assert (p['kind'],p['type']) in [(10,29),(10,31),(10,1),(5,2),(5,27),(8,14)],'unsupported supply'
 return w,h
def generate(v):
 w,h=validate(v);canonical=json.dumps(v,sort_keys=True,separators=(',',':')).encode();digest=hashlib.sha256(canonical).hexdigest()
 out=['/* Generated by generate-level.py; runtime import, NOT Dungeon.DAT. SHA256 '+digest+' */','#define COOP_NAME '+json.dumps(v['name']),f'#define COOP_W {w}',f'#define COOP_H {h}','static const char *coop_rows[] = {'+','.join(json.dumps(r) for r in v['rows'])+'};']
 for key in ['starts','activators','exits']:
  ps=v[key];out.append('static const int coop_'+key+'[2][2] = {'+','.join('{%d,%d}'%(p['x'],p['y']) for p in ps)+'};')
 out.append('static const int coop_dirs[2] = {'+','.join(str(p['direction']) for p in v['starts'])+'};')
 out.append('static const int coop_door[2] = {%d,%d};'%(v['door']['x'],v['door']['y']))
 out.append('#define COOP_ENCOUNTER_COUNT %d'%len(v.get('encounters',[])))
 out.append('static const int coop_encounters[][6] = {'+','.join('{%d,%d,%d,%d,%d,%d}'%(e['x'],e['y'],e['type'],e['count'],e['hp'],e['direction']) for e in v.get('encounters',[]))+'};')
 for key,n in [('buttonDoors',2),('secretWalls',2),('supplies',5)]:
  fields=['x','y'] if n==2 else ['x','y','kind','type','charges']
  out.append('#define COOP_'+key.upper()+'_COUNT '+str(len(v.get(key,[]))))
  out.append('static const int coop_'+key+'[]['+str(n)+'] = {'+','.join('{'+','.join(str(p[k]) for k in fields)+'}' for p in v.get(key,[]))+'};')
 return chr(10).join(out)+chr(10)
if __name__=='__main__':
 try:Path(sys.argv[2] if len(sys.argv)>2 else 'level.generated.h').write_text(generate(json.loads(Path(sys.argv[1] if len(sys.argv)>1 else 'level.json').read_text())))
 except (AssertionError,KeyError,TypeError,ValueError,IndexError) as e:sys.exit('INVALID LEVEL: '+str(e))
